#!/usr/bin/env node
/**
 * migrations/ALL.sql must be exactly the numbered migration files, in order.
 *
 *   node scripts/check-migrations.js           # exit 1 if ALL.sql is stale
 *   node scripts/check-migrations.js --write   # regenerate ALL.sql
 *
 * Order is the filename sort (NNN_name.sql; two files sharing a number run in
 * name order, e.g. 001_initial_schema before 001_whapi_bot_conversations).
 * Each file is copied verbatim under a three-line banner naming it, so a
 * failure in the Supabase SQL editor points at the file it came from.
 *
 * Numbers with no file (e.g. 017, reserved) are fine and only reported.
 * Never edit ALL.sql by hand: edit/add the numbered file and run --write.
 */

const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'migrations');
const ALL = path.join(DIR, 'ALL.sql');
const NUMBERED = /^(\d{3})_[a-z0-9_]+\.sql$/;
const RULE = '-- ' + '─'.repeat(61);

const HEADER = [
  '-- ALL.sql — every numbered migration in this directory, in order.',
  '-- GENERATED by scripts/check-migrations.js --write. Do not edit by hand:',
  '-- change the numbered file and regenerate. tests/migrations.test.js fails',
  '-- when this file drifts from the numbered files.',
  '--',
  '-- For a fresh Supabase project: SQL Editor → paste → run. For an existing',
  '-- database apply only the numbered files it has not had yet (see',
  '-- docs/RELEASE-*.md).',
  ''
].join('\n');

function migrationFiles(dir = DIR) {
  return fs
    .readdirSync(dir)
    .filter((f) => NUMBERED.test(f))
    .sort();
}

function build(dir = DIR) {
  const parts = migrationFiles(dir).map((file) => {
    let body = fs.readFileSync(path.join(dir, file), 'utf8');
    if (!body.endsWith('\n')) body += '\n';
    return `${RULE}\n-- ${file}\n${RULE}\n${body}`;
  });
  return `${HEADER}\n${parts.join('\n')}`;
}

function check(dir = DIR) {
  const problems = [];
  const all = path.join(dir, 'ALL.sql');
  const stray = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.sql') && f !== 'ALL.sql' && !NUMBERED.test(f));
  if (stray.length) problems.push(`not named NNN_name.sql: ${stray.join(', ')}`);

  const expected = build(dir);
  const actual = fs.existsSync(all) ? fs.readFileSync(all, 'utf8') : null;
  if (actual === null) problems.push('ALL.sql is missing');
  else if (actual !== expected) {
    const missing = migrationFiles(dir).filter(
      (f) => !actual.includes(fs.readFileSync(path.join(dir, f), 'utf8').trim())
    );
    problems.push(
      'ALL.sql is not the ordered concatenation of the numbered files' +
        (missing.length ? ` (missing: ${missing.join(', ')})` : ' (content or order differs)')
    );
  }

  const numbers = [...new Set(migrationFiles(dir).map((f) => Number(f.slice(0, 3))))];
  const gaps = [];
  for (let n = 1; n < Math.max(0, ...numbers); n += 1) if (!numbers.includes(n)) gaps.push(String(n).padStart(3, '0'));

  return { ok: problems.length === 0, problems, gaps, files: migrationFiles(dir) };
}

if (require.main === module) {
  if (process.argv.includes('--write')) {
    fs.writeFileSync(ALL, build());
    console.log(`wrote migrations/ALL.sql from ${migrationFiles().length} files`);
    process.exit(0);
  }
  const result = check();
  if (result.gaps.length) console.log(`note: unused migration numbers: ${result.gaps.join(', ')}`);
  if (!result.ok) {
    for (const p of result.problems) console.error(`migrations: ${p}`);
    console.error('fix: node scripts/check-migrations.js --write');
    process.exit(1);
  }
  console.log(`migrations: ALL.sql matches ${result.files.length} numbered files`);
}

module.exports = { build, check, migrationFiles };
